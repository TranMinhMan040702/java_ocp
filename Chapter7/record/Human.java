/**
 * Example: Compare the class and record declarations
 */

public class Human {
    private String sex;
    private int age;

    public Human(String sex, int age) {
        this.sex = sex;
        this.age = age;
    }

    public String getSex() {
        return this.sex;
    }

    public int getAge() {
        return this.age;
    }
}